"""AnalytIQ Reports - Server-side PDF export renderer using ReportLab."""

import io
from typing import Any

from app.models.report import Report
from app.reports.contracts import (
    HeadingBlock,
    LimitationNoticeBlock,
    ParagraphBlock,
    ReportDocument,
    ResultTableBlock,
    ScalarMetricBlock,
    VerifiedFindingBlock,
)
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


class NumberedCanvas:
    """Canvas wrapper that records total pages and draws headers and footers."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        self.args = args
        self.kwargs = kwargs


def draw_page_decorations(canvas: Any, doc: Any) -> None:
    """Draw professional page headers and footers on every page."""
    canvas.saveState()
    canvas.setFont("Helvetica", 9)
    canvas.setFillColor(colors.HexColor("#71717A"))  # Zinc 500

    # Header
    canvas.drawString(54, doc.height + 72, "AnalytIQ — Intelligent Analysis. Verified Insights.")
    canvas.setStrokeColor(colors.HexColor("#E4E4E7"))
    canvas.setLineWidth(0.5)
    canvas.line(54, doc.height + 66, doc.width + 54, doc.height + 66)

    # Footer
    page_num = canvas.getPageNumber()
    footer_text = f"Page {page_num}"
    canvas.drawRightString(doc.width + 54, 36, footer_text)
    canvas.drawString(54, 36, "Confidential — Generated by AnalytIQ Verification Engine")
    canvas.line(54, 48, doc.width + 54, 48)

    canvas.restoreState()


class PDFExporter:
    """Renders structured ReportDocument into an accessible, publication-grade PDF."""

    @classmethod
    def export_report_to_pdf(cls, report: Report) -> bytes:
        """Render a Report entity into an A4 PDF byte array."""
        doc = ReportDocument.model_validate(report.document)
        buffer = io.BytesIO()

        # SimpleDocTemplate A4 margins
        pdf = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()

        # Custom typography hierarchy
        title_style = ParagraphStyle(
            "ReportTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            textColor=colors.HexColor("#09090B"),  # Zinc 950
            spaceAfter=6,
        )

        meta_style = ParagraphStyle(
            "ReportMeta",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#71717A"),
            spaceAfter=14,
        )

        h1_style = ParagraphStyle(
            "SectionH1",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=15,
            leading=18,
            textColor=colors.HexColor("#18181B"),
            spaceBefore=14,
            spaceAfter=8,
            keepWithNext=True,
        )

        h2_style = ParagraphStyle(
            "SectionH2",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#27272A"),
            spaceBefore=10,
            spaceAfter=6,
            keepWithNext=True,
        )

        body_style = ParagraphStyle(
            "ReportBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#3F3F46"),
            spaceAfter=8,
        )

        finding_style = ParagraphStyle(
            "VerifiedFinding",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#065F46"),  # Emerald 800
            backColor=colors.HexColor("#ECFDF5"),  # Emerald 50
            borderColor=colors.HexColor("#A7F3D0"),
            borderWidth=0.5,
            borderPadding=8,
            spaceAfter=8,
            borderRadius=4,
        )

        limitation_style = ParagraphStyle(
            "LimitationNotice",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=13,
            textColor=colors.HexColor("#9A3412"),  # Amber 800
            backColor=colors.HexColor("#FFFBEB"),  # Amber 50
            borderColor=colors.HexColor("#FDE68A"),
            borderWidth=0.5,
            borderPadding=6,
            spaceAfter=6,
            borderRadius=4,
        )

        story: list[Any] = []

        # 1. Header Banner & Title
        status_str = (report.status or "ready").capitalize()
        story.append(Paragraph(doc.metadata.title, title_style))
        meta_line = (
            f"<b>Dataset:</b> {doc.metadata.dataset_name} &nbsp;|&nbsp; "
            f"<b>Generated:</b> {doc.metadata.generated_at.strftime('%B %d, %Y')} &nbsp;|&nbsp; "
            f"<b>Status:</b> {status_str}"
        )
        story.append(Paragraph(meta_line, meta_style))
        if doc.metadata.description:
            story.append(Paragraph(doc.metadata.description, body_style))
        story.append(
            HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E4E4E7"), spaceAfter=14)
        )

        # 2. Executive Summary
        story.append(Paragraph("Executive Summary", h1_style))
        story.append(Paragraph(doc.executive_summary, body_style))
        story.append(Spacer(1, 10))

        # 3. Dataset Overview Card
        overview_text = (
            f"<b>Dataset Overview:</b> {doc.dataset_overview.dataset_name} contains "
            f"<b>{doc.dataset_overview.row_count}</b> rows and "
            f"<b>{doc.dataset_overview.column_count}</b> columns."
        )
        story.append(Paragraph(overview_text, body_style))
        story.append(Spacer(1, 10))

        # 4. Report Sections
        for sec in doc.sections:
            if not sec.visible:
                continue

            section_elements: list[Any] = []
            section_elements.append(Paragraph(sec.title, h1_style))

            for blk in sec.blocks:
                if isinstance(blk, HeadingBlock):
                    if blk.text != sec.title:
                        section_elements.append(Paragraph(blk.text, h2_style))
                elif isinstance(blk, ParagraphBlock):
                    section_elements.append(Paragraph(blk.text, body_style))
                elif isinstance(blk, VerifiedFindingBlock):
                    text = f"<b>[VERIFIED]</b> {blk.finding_text}"
                    section_elements.append(Paragraph(text, finding_style))
                elif isinstance(blk, ScalarMetricBlock):
                    metric_html = (
                        f"<b>Metric:</b> {blk.label}: <b>{blk.value}</b> "
                        f"{'(' + blk.unit + ')' if blk.unit else ''}"
                    )
                    section_elements.append(Paragraph(metric_html, body_style))
                elif isinstance(blk, LimitationNoticeBlock):
                    text = f"<b>Limitation:</b> {blk.notice_text}"
                    section_elements.append(Paragraph(text, limitation_style))
                elif isinstance(blk, ResultTableBlock):
                    section_elements.append(Paragraph("<b>Result Table:</b>", h2_style))
                    # Render Table Flowable
                    headers = [c.name for c in blk.columns]
                    table_data: list[list[Any]] = [headers]
                    for r in blk.rows[:25]:  # Preview up to 25 rows in PDF table
                        table_data.append([str(cell if cell is not None else "") for cell in r])

                    col_w = (doc.metadata.title and 480 / max(len(headers), 1)) or 100
                    pdf_table = Table(table_data, colWidths=[col_w] * len(headers), repeatRows=1)
                    pdf_table.setStyle(
                        TableStyle(
                            [
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F4F4F5")),
                                ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#18181B")),
                                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                                ("FONTSIZE", (0, 0), (-1, -1), 8),
                                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                                ("TOPPADDING", (0, 0), (-1, -1), 4),
                                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E4E4E7")),
                                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                            ]
                        )
                    )
                    section_elements.append(pdf_table)
                    if blk.truncated:
                        trunc_msg = (
                            f"<i>Showing 25 of {blk.returned_row_count} rows (truncated).</i>"
                        )
                        section_elements.append(Paragraph(trunc_msg, meta_style))

            story.append(KeepTogether(section_elements))
            story.append(Spacer(1, 14))

        # 5. Methodology & Evidence Appendix
        if doc.methodology:
            story.append(Paragraph("Methodology & Analytical Verification", h1_style))
            story.append(Paragraph(doc.methodology.note, body_style))
            story.append(Spacer(1, 10))

        if doc.evidence_appendix:
            story.append(Paragraph("Evidence Appendix", h1_style))
            for ev in doc.evidence_appendix:
                fp_short = ev.result_fingerprint[:12] if ev.result_fingerprint else "None"
                ev_text = (
                    f"<b>Request:</b> {ev.request_id} &nbsp;|&nbsp; "
                    f"<b>Verification:</b> {ev.verification_status} &nbsp;|&nbsp; "
                    f"<b>Fingerprint:</b> <code>{fp_short}</code>"
                )
                story.append(Paragraph(ev_text, body_style))

        # Build PDF with page decorations
        pdf.build(story, onFirstPage=draw_page_decorations, onLaterPages=draw_page_decorations)
        return buffer.getvalue()
