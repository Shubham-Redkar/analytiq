"""Strongly typed contracts for the AnalytIQ Analytical Engine."""

import uuid
from datetime import UTC, datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class PlanStatus(StrEnum):
    """Lifecycle status of a structured analytical plan."""

    READY = "ready"
    NEEDS_CLARIFICATION = "needs_clarification"
    UNSUPPORTED = "unsupported"


class AnalyticalOperation(StrEnum):
    """Normalized analytical operation categories."""

    AGGREGATION = "aggregation"
    GROUPED_AGGREGATION = "grouped_aggregation"
    FILTERING = "filtering"
    SORTING = "sorting"
    RANKING = "ranking"
    DISTRIBUTION = "distribution"
    DISTINCT_VALUES = "distinct_values"
    DESCRIPTIVE_STATISTICS = "descriptive_statistics"
    TIME_SERIES = "time_series"
    COMPARISON = "comparison"
    GENERAL_QUERY = "general_query"


class ColumnContext(BaseModel):
    """Contextual representation of a dataset column for analytical planning."""

    name: str
    physical_type: str
    logical_type: str
    nullable: bool = True
    distinct_count: int | None = None
    sample_values: list[Any] = Field(default_factory=list)


class DatasetAnalyticalContext(BaseModel):
    """Data-minimized analytical context bound to the logical relation 'dataset'."""

    relation_name: str = "dataset"
    dataset_name: str
    row_count: int
    column_count: int
    columns: list[ColumnContext]
    dialect: str = "duckdb"


class StructuredAnalyticalPlan(BaseModel):
    """Structured plan generated by LLM representing analytical intent and proposed SQL."""

    model_config = ConfigDict(extra="forbid")

    status: PlanStatus
    intent: str = Field(description="Normalized concise summary of analytical intent.")
    operation: AnalyticalOperation | None = Field(
        default=None,
        description="Analytical operation category when status is ready.",
    )
    referenced_columns: list[str] = Field(
        default_factory=list,
        description="List of exact dataset columns referenced by the analytical query.",
    )
    sql: str | None = Field(
        default=None,
        description="Proposed read-only DuckDB SQL query querying 'dataset' when status is ready.",
    )
    assumptions: list[str] = Field(
        default_factory=list,
        description="Explicit assumptions made while generating the analytical plan.",
    )
    clarification_question: str | None = Field(
        default=None,
        description="Question to present to user when status is needs_clarification.",
    )
    unsupported_reason: str | None = Field(
        default=None,
        description="Safe explanatory reason when status is unsupported.",
    )


class SQLValidationCategory(StrEnum):
    """Categorized status of deterministic SQL validation."""

    VALID = "valid"
    SYNTAX_ERROR = "syntax_error"
    PROHIBITED_STATEMENT = "prohibited_statement"
    UNAUTHORIZED_RELATION = "unauthorized_relation"
    UNKNOWN_COLUMN = "unknown_column"
    UNAPPROVED_FUNCTION = "unapproved_function"
    COMPLEXITY_LIMIT_EXCEEDED = "complexity_limit_exceeded"
    RESOURCE_VIOLATION = "resource_violation"


class SQLValidationResult(BaseModel):
    """Deterministic result of AST-based SQL security analysis."""

    is_valid: bool
    category: SQLValidationCategory
    error_message: str | None = None
    normalized_sql: str | None = None
    referenced_columns: list[str] = Field(default_factory=list)
    referenced_tables: list[str] = Field(default_factory=list)
    has_user_limit: bool = False
    requested_limit: int | None = None


class ExecutionEvidence(BaseModel):
    """Traceable execution provenance and verifiable metadata for analytical results."""

    dataset_id: uuid.UUID
    dataset_fingerprint: str
    schema_fingerprint: str
    executed_sql: str
    executed_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    row_count: int
    column_count: int
    truncated: bool = False
    result_fingerprint: str
    query_duration_ms: float
    total_duration_ms: float
    provider: str
    model: str
    prompt_version: str
    correction_attempts: int = 0
    token_usage: dict[str, int | None] = Field(default_factory=dict)


class AnalyticalResultColumn(BaseModel):
    """Column definition for analytical query results."""

    name: str
    type: str


class AnalyticalQueryResult(BaseModel):
    """Final verified analytical response returned by the API."""

    request_id: str
    dataset_id: uuid.UUID
    status: str  # "completed", "needs_clarification", "unsupported", "failed"
    question: str
    intent: str
    executed_sql: str | None = None
    columns: list[AnalyticalResultColumn] = Field(default_factory=list)
    rows: list[list[Any]] = Field(default_factory=list)
    returned_row_count: int = 0
    total_row_count: int | None = None
    truncated: bool = False
    clarification_question: str | None = None
    unsupported_reason: str | None = None
    error_message: str | None = None
    evidence: ExecutionEvidence | None = None
